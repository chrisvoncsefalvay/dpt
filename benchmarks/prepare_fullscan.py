"""Prepare the full chest acquisition and bind a fresh measurement configuration."""

from __future__ import annotations

import argparse
import hashlib
import json
from datetime import UTC, datetime
from pathlib import Path

import numpy as np

from benchmarks import fullscan_inputs
from benchmarks.fullscan_inputs import load_prepared, prepare, sha256


def raw_view(index):
    theta = 2 * np.pi * index / 360
    row = 2 * (np.arange(512, dtype=np.float64) + 0.5) / 512 - 1
    column = row.copy()
    return (
        1
        + 0.20 * np.sin(theta)
        + 0.10 * np.cos(2 * theta)
        + 0.15 * row[:, None]
        + 0.10 * column[None, :]
        + 0.05 * np.sin(theta) * column[None, :]
    )


def write_cotangent(output, contract_path, contract):
    normaliser = sum(float(np.sum(raw_view(k), dtype=np.float64)) for k in range(360))
    result = np.lib.format.open_memmap(output, mode="w+", dtype=np.float32, shape=(360, 512, 512))
    raw_hash = hashlib.sha256()
    for index in range(360):
        result[index] = (raw_view(index) / normaliser).astype(np.float32)
        raw_hash.update(memoryview(result[index]).cast("B"))
    result.flush()
    metadata = {
        "prepared_at_utc": datetime.now(UTC).isoformat(),
        "file": output.name,
        "shape": list(result.shape),
        "dtype": str(result.dtype),
        "sha256": sha256(output),
        "raw_sha256": raw_hash.hexdigest(),
        "contract_sha256": sha256(contract_path),
        "formula": contract["cotangent"],
        "raw_l1_normaliser_fp64": normaliser,
        "stored_l1_fp64": float(np.sum(result, dtype=np.float64)),
        "minimum": float(result.min()),
        "maximum": float(result.max()),
        "generator_sha256": sha256(Path(__file__)),
        "numpy_version": np.__version__,
    }
    output.with_suffix(".json").write_text(json.dumps(metadata, indent=2) + "\n")
    return metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ct", type=Path, help="Pinned CTChest NIfTI")
    parser.add_argument("--source-nrrd", type=Path, help="Pinned original CTChest NRRD")
    parser.add_argument("--prepared", type=Path, help="Reuse an existing verified fullscan input")
    parser.add_argument("--output", type=Path, required=True, help="New external results directory")
    parser.add_argument(
        "--settings",
        type=Path,
        default=Path(__file__).parent / "config/fullscan.json",
    )
    args = parser.parse_args()
    if args.prepared is not None and (args.ct is not None or args.source_nrrd is not None):
        parser.error("choose --prepared or both --ct and --source-nrrd")
    if args.prepared is None and (args.ct is None or args.source_nrrd is None):
        parser.error("supply both --ct and --source-nrrd, or --prepared")
    args.output.mkdir(parents=True, exist_ok=False)
    if args.prepared is None:
        inputs = args.output / "inputs"
        metadata = prepare(args.ct, args.source_nrrd, inputs)
    else:
        inputs = args.prepared.resolve()
        metadata = load_prepared(inputs).metadata
    contract = json.loads(args.settings.read_text())
    expected = contract["field"]["file_sha256"]
    if metadata["arrays"]["attenuation"]["sha256"] != expected:
        raise ValueError("resampled attenuation differs from the measured benchmark field")
    contract.update(
        frozen_at_utc=datetime.now(UTC).isoformat(),
        input_metadata_sha256=sha256(inputs / "metadata.json"),
        input_helper_sha256=sha256(Path(fullscan_inputs.__file__)),
    )
    contract_path = args.output / "contract.json"
    contract_path.write_text(json.dumps(contract, indent=2) + "\n")
    seed_path = args.output / "cotangent.npy"
    seed = write_cotangent(seed_path, contract_path, contract)
    print(
        json.dumps(
            {
                "inputs": str(inputs),
                "contract": str(contract_path),
                "cotangent": str(seed_path),
                "cotangent_sha256": seed["sha256"],
                "measurement_timestamps": "generated by the benchmark when it actually runs",
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
